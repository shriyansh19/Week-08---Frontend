// Problem 3: Use REPL – Add two Random Dice Numbers and Print the Result

// Generate two random dice numbers
let dice1 = Math.floor(Math.random() * 6) + 1;
let dice2 = Math.floor(Math.random() * 6) + 1;

// Add the two dice numbers
let sumOfDice = dice1 + dice2;

// Print the result
console.log("Dice 1:", dice1);
console.log("Dice 2:", dice2);
console.log("Sum of Two Dice Numbers:", sumOfDice);